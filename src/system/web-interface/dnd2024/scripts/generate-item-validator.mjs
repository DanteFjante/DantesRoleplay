import { readFile, writeFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
const query = JSON.parse(await readFile(new URL("../../../../../catalog/applications/dnd2024/queries/data/dnd2024.query.inventory-item-details.json", import.meta.url), "utf8"));
// Conditional subschemas narrow properties whose types are declared on the
// enclosing schema; do not rewrite the catalog merely for AJV's lint rule.
const ajv = new Ajv2020({ strict: true, strictTypes: false, code: { source: true, esm: true } });
const generated = standalone(ajv, ajv.compile(query.outputSchema))
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length.default ?? ucs2length');
if (generated.includes("require(")) throw new Error("Unexpected validator runtime dependency.");
const output = '// Generated by scripts/generate-item-validator.mjs from the catalog Details query.\n' +
  'import ucs2length from "ajv/dist/runtime/ucs2length.js";\n' +
  `export const contract = ${JSON.stringify({ id: query.id, ...query.projection })};\n` + generated + '\n';
const target = new URL("../src/server/item-details-validator.js", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")).replace(/\r\n/g, "\n") !== output) throw new Error("Item validator drift: regenerate from the catalog.");
} else await writeFile(target, output);
